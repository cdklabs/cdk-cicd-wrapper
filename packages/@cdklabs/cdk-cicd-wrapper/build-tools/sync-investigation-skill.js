// Copy the repo's skills/cdk-cicd-pipeline-failure-investigation into src/engine/devops-agent/
// investigation-skill.generated.ts, so the `knowledge` level of `devopsAgent` can publish it: jsii ships
// only compiled TypeScript, never the repo-root skills/ directory. test/engine/devops-agent/
// investigation-skill.test.ts fails when the two drift apart. Run: node build-tools/sync-investigation-skill.js

const fs = require('fs');
const path = require('path');

const PACKAGE = path.resolve(__dirname, '..');
const SKILL = path.resolve(PACKAGE, '..', '..', '..', 'skills', 'cdk-cicd-pipeline-failure-investigation');
const TARGET = path.join(PACKAGE, 'src', 'engine', 'devops-agent', 'investigation-skill.generated.ts');

function files(dir) {
  return fs
    .readdirSync(dir, { withFileTypes: true })
    .flatMap((entry) => {
      const full = path.join(dir, entry.name);
      return entry.isDirectory() ? files(full) : entry.name.endsWith('.md') ? [full] : [];
    })
    .sort();
}

/** The skill's files as { path, content }, paths relative to the skill directory with `/` separators. */
function skillFiles() {
  return files(SKILL).map((file) => ({
    path: path.relative(SKILL, file).split(path.sep).join('/'),
    content: fs.readFileSync(file, 'utf-8'),
  }));
}

function render() {
  return [
    '// Copyright Amazon.com, Inc. or its affiliates. All Rights Reserved.',
    '// SPDX-License-Identifier: Apache-2.0',
    '//',
    '// GENERATED by build-tools/sync-investigation-skill.js from skills/cdk-cicd-pipeline-failure-investigation.',
    '// Do not edit; change the skill and re-run the script.',
    '',
    '/** The cdk-cicd-pipeline-failure-investigation skill, file by file. */',
    `export const INVESTIGATION_SKILL_FILES: ReadonlyArray<{ readonly path: string; readonly content: string }> = ${JSON.stringify(skillFiles(), null, 2)};`,
    '',
  ].join('\n');
}

module.exports = { render, skillFiles, TARGET };

if (require.main === module) {
  fs.writeFileSync(TARGET, render());
  console.log(`wrote ${path.relative(PACKAGE, TARGET)}`);
}
